import assert from 'node:assert/strict';
import { initialState, validState, transition, STORAGE_KEY } from '../src/scripts/blackbeards-treasure-archer/core.mjs';

let s = initialState();
let checks = 0;
function check(condition, message) { assert.ok(condition, message); checks++; }
function act(action, value) { const result = transition(s, action, value); s = result.state; check(validState(s), `Valid state after ${action}`); return result.message; }
check(STORAGE_KEY.startsWith('tfi-blackbeard-'), 'Storage key scoped to game');
check(validState(s), 'Fresh state valid');
check(!validState({ ...s, chart: true }), 'Forged chart state rejected');
check(!validState({ ...s, won: true }), 'Forged win rejected');
check(!validState({ ...s, route: ['moon', 'moon'] }), 'Malformed route rejected');
check(!validState({ ...s, bearings: [0, -1, 4] }), 'Malformed bearings rejected');
check(!validState({ ...s, coins: ['moon', 'moon'] }), 'Repeated coin rejected');
check(act('open').includes('key'), 'Chest gate explains key');
check(act('coin', 'moon').includes('locked'), 'Weights gated');
check(act('rotate', 0).includes('sealed'), 'Astrolabe gate explains chart');
check(act('align').includes('chart'), 'Cannot align before chart');
act('route', 'moon');
act('route', 'lantern');
check(s.route.length === 0, 'Wrong landmark resets without softlock');
act('route', 'moon'); act('route', 'reef');
check(!s.chart && !s.key, 'Opening route not counted as solved');
check(act('route', 'lantern').includes('E → S → W'), 'Chart gives next puzzle clue');
check(s.chart && !s.instrument, 'Chart only advances its own stage');
act('route', 'moon');
check(s.route.length === 3, 'Repeated route cannot regress');
check(act('align').includes('refuse'), 'Wrong bearings get feedback');
act('rotate', 0); act('rotate', 1); act('rotate', 1);
act('rotate', 2); act('rotate', 2); act('rotate', 2);
check(s.bearings.join(',') === '1,2,3', 'Dial rotation produces expected bearings');
act('align');
check(s.instrument && s.key && !s.won, 'Instrument yields key but not win');
act('rotate', 0);
check(s.bearings[0] === 1, 'Solved dial ignores repeated clicks');
act('coin', 'lantern'); act('coin', 'reef');
check(act('open').includes('wrong'), 'Wrong pair not accepted');
check(!s.won, 'Wrong chest attempt not a win');
act('coin', 'lantern'); act('coin', 'moon');
check(s.coins.length === 2, 'Weights can be removed and replaced');
check(act('open').includes('opens'), 'Correct pair opens chest');
check(s.won, 'Win flag set');
act('coin', 'moon'); act('open');
check(s.won && s.coins.length === 2, 'Post-win actions cannot alter prize');
const saved = JSON.parse(JSON.stringify(s));
check(validState(saved), 'Completed state can be restored safely');
s = initialState();
check(validState(s) && !s.chart && !s.key && !s.won && s.coins.length === 0, 'Restart resets all game rules');
check(act('route', 'moon').includes('Course held'), 'Fresh run can progress after restart');
console.log(`Blackbeard game verification: ${checks} assertions passed; gates, incorrect attempts, complete chain, repeats, restore and reset.`);
